H=pathlib.Path('/root/.hermes'); P=pathlib.Path('/root/workspace/科武纪元')
for line in (H/'.env').read_text().splitlines():
    if '=' in line and not line.startswith('#'):
        k,v=line.split('=',1); os.environ.setdefault(k,v)
cfg=yaml.safe_load((H/'config.yaml').read_text())['providers']['xiaomi']
base=cfg['base_url'].rstrip('/'); key=cfg.get('api_key') or os.environ.get(cfg.get('key_env','')); model='mimo-v2.5'
raw=P/'审核记录/六角色外审/raw'; raw.mkdir(parents=True,exist_ok=True)

def call(ch, old, issues):
    prompt=f'''角色: 作者。任务: 只改第{ch}章以下片段，修复审核硬伤。不要解释，不新增剧情，不改主线。输出替换后的正文片段。
硬约束: 去文艺比喻；用动作/物理反馈；补证物链/技术可信度；保留原段功能。
审核问题:
{issues}
原片段:
{old}
'''
    payload={'model':model,'messages':[{'role':'user','content':prompt}],'max_tokens':2200}
    req=urllib.request.Request(base+'/chat/completions',data=json.dumps(payload,ensure_ascii=False).encode(),headers={'Authorization':'Bearer '+key,'Content-Type':'application/json'})
    with urllib.request.urlopen(req,timeout=180) as r: d=json.loads(r.read().decode())
    content=d['choices'][0]['message'].get('content','')
    (raw/f'第{ch}_author_fix_mimo.json').write_text(json.dumps({'prompt':prompt,'content':content,'raw':d},ensure_ascii=False,indent=2))
    print(f'---CH{ch}---\n{content}\n')

